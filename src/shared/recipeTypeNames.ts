function tailOf(typeId: string): { ns: string; tail: string } {
  const i = typeId.indexOf(':')
  if (i < 0) return { ns: '', tail: typeId }
  return { ns: typeId.slice(0, i), tail: typeId.slice(i + 1) }
}

